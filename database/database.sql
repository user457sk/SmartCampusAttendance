-- SmartCampus Database
-- PostgreSQL / Supabase
-- ============================================================

-- ============================================================
-- USERS
-- ============================================================

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    username VARCHAR(100) NOT NULL UNIQUE,

    email VARCHAR(255) NOT NULL UNIQUE,

    password_hash TEXT NOT NULL,

    role VARCHAR(20) NOT NULL
        CHECK (role IN ('student', 'teacher', 'admin')),

    account_status VARCHAR(20) NOT NULL DEFAULT 'approved'
        CHECK (account_status IN ('pending', 'approved', 'rejected')),

    profile_pic TEXT,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE users
    ADD COLUMN IF NOT EXISTS account_status VARCHAR(20) NOT NULL DEFAULT 'approved'
    CHECK (account_status IN ('pending', 'approved', 'rejected'));


-- ============================================================
-- STUDENTS
-- ============================================================

CREATE TABLE IF NOT EXISTS students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id BIGINT UNIQUE,

    roll_number VARCHAR(100) NOT NULL UNIQUE,

    full_name VARCHAR(150) NOT NULL,

    course VARCHAR(100),

    branch VARCHAR(100),

    semester INTEGER DEFAULT 1,

    phone VARCHAR(30),

    CONSTRAINT fk_students_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE SET NULL
);


-- ============================================================
-- TEACHERS
-- ============================================================

CREATE TABLE IF NOT EXISTS teachers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id BIGINT NOT NULL UNIQUE,

    full_name VARCHAR(150) NOT NULL,

    department VARCHAR(150),

    employee_id VARCHAR(100) UNIQUE,

    phone VARCHAR(30),

    CONSTRAINT fk_teachers_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE CASCADE
);


-- ============================================================
-- SUBJECTS
-- ============================================================

CREATE TABLE IF NOT EXISTS subjects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    subject_code VARCHAR(50) NOT NULL UNIQUE,

    subject_name VARCHAR(150) NOT NULL,

    course VARCHAR(100),

    branch VARCHAR(100),

    semester INTEGER
);


-- ============================================================
-- TEACHER SUBJECTS
-- ============================================================

CREATE TABLE IF NOT EXISTS teacher_subjects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    teacher_id BIGINT NOT NULL,

    subject_id BIGINT NOT NULL,

    CONSTRAINT fk_teacher_subjects_teacher
        FOREIGN KEY (teacher_id)
        REFERENCES teachers(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_teacher_subjects_subject
        FOREIGN KEY (subject_id)
        REFERENCES subjects(id)
        ON DELETE CASCADE,

    CONSTRAINT unique_teacher_subject
        UNIQUE (teacher_id, subject_id)
);


-- ============================================================
-- ATTENDANCE
-- ============================================================

CREATE TABLE IF NOT EXISTS attendance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    student_id BIGINT NOT NULL,

    subject_id BIGINT NOT NULL,

    teacher_id BIGINT NOT NULL,

    date DATE NOT NULL,

    status VARCHAR(20) NOT NULL
        CHECK (status IN ('Present', 'Absent')),

    marked_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_attendance_student
        FOREIGN KEY (student_id)
        REFERENCES students(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_attendance_subject
        FOREIGN KEY (subject_id)
        REFERENCES subjects(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_attendance_teacher
        FOREIGN KEY (teacher_id)
        REFERENCES teachers(id)
        ON DELETE CASCADE,

    CONSTRAINT unique_student_subject_date
        UNIQUE (student_id, subject_id, date)
);


-- ============================================================
-- ENROLLMENTS
-- ============================================================

CREATE TABLE IF NOT EXISTS enrollments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    student_id BIGINT NOT NULL,

    subject_id BIGINT NOT NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'approved', 'rejected')),

    requested_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    reviewed_at TIMESTAMP,

    reviewed_by BIGINT,

    rejection_reason TEXT,

    CONSTRAINT fk_enrollments_student
        FOREIGN KEY (student_id)
        REFERENCES students(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_enrollments_subject
        FOREIGN KEY (subject_id)
        REFERENCES subjects(id)
        ON DELETE CASCADE,

    CONSTRAINT unique_student_subject_enrollment
        UNIQUE (student_id, subject_id)
);


-- ============================================================
-- INDEXES
-- ============================================================

CREATE INDEX IF NOT EXISTS idx_attendance_student
    ON attendance(student_id);


CREATE INDEX IF NOT EXISTS idx_attendance_subject
    ON attendance(subject_id);


CREATE INDEX IF NOT EXISTS idx_attendance_date
    ON attendance(date);


CREATE INDEX IF NOT EXISTS idx_teacher_subjects_teacher
    ON teacher_subjects(teacher_id);


CREATE INDEX IF NOT EXISTS idx_teacher_subjects_subject
    ON teacher_subjects(subject_id);


CREATE INDEX IF NOT EXISTS idx_enrollments_student
    ON enrollments(student_id);


CREATE INDEX IF NOT EXISTS idx_enrollments_subject
    ON enrollments(subject_id);


CREATE INDEX IF NOT EXISTS idx_enrollments_status
    ON enrollments(status);